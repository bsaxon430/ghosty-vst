#!/usr/bin/env python3
"""Poltergeist 2 (GhostBlock) - SUB: makes the golden values the C++ port of Subhoofer is checked against.

  python3 -I make-golden.py            extract, build (cargo, no network: no dependencies), run, write the header
  python3 -I make-golden.py --check    the same, but compare with the header in the tree instead of writing it

It takes upstream's Rust source TEXT from libs/ghostblock-sub/subhoofer/src/lib.rs (checked against the pinned SHA-256)
- the enum AlgorithmType, the six free functions and, out of Subhoofer::process, the four blocks of the harmonic path
(the `match h_algorithm`, "Hardness Saturation", the DC high-pass, the dry/wet + output gain) - and writes them, verbatim,
into src/upstream_extract.rs inside a small frame that stands in for the plugin (the struct with the fields those blocks
use; sub_bump and sub_gain are 0: the subharmonic generator is not part of the port). SweetenX.rs is compiled as it is.
"""
import hashlib, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.join(HERE, "..", "subhoofer", "src", "lib.rs")
SWEET = os.path.join(HERE, "..", "subhoofer", "src", "SweetenX.rs")
OUT = os.path.join(HERE, "..", "..", "..", "src", "ghostblock", "sub", "tests", "subhoofer-golden.h")
PIN = {LIB: "ffc4f133a1366938f0297f27cb92ed6c22994afe270f9c082e586abe53b80ff9",
       SWEET: "a9f00d6db59817bac2ef38de85b4d012b5044b37a1fe5661eb05b755367d8a35"}


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def block_from(text, start_marker, open_at=None):
    """the text from start_marker to the brace that closes the first '{' at or after open_at (default: the marker)"""
    a = text.index(start_marker)
    i = text.index("{", a if open_at is None else text.index(open_at, a))
    depth = 0
    while True:
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[a:i + 1], i + 1
        i += 1


def lines_between(text, first, last):
    a = text.index(first)
    b = text.index(last, a) + len(last)
    return text[a:b]


def main():
    for p, want in PIN.items():
        if sha(p) != want:
            sys.exit("the vendored upstream file changed: " + p)
    t = open(LIB, encoding="utf-8").read()
    enum, _ = block_from(t, "pub enum AlgorithmType{")
    enum = "\n".join(l for l in enum.splitlines() if "#[name" not in l)
    fns = [block_from(t, "fn %s(" % n)[0] for n in
           ("chebyshev_tape", "tape_saturation", "b_bass_saturation", "c_bass_saturation", "custom_sincos_saturation", "leaf_saturation")]
    small = lines_between(t, "if in_l.abs() < 1.18e-23", "if in_r.abs() < 1.18e-23 { in_r = 0.1 * 1.18e-17; }")
    match, _ = block_from(t, "match h_algorithm {")
    hard_if, end = block_from(t, "if h_algorithm == AlgorithmType::ABass3 {")
    hard_else, _ = block_from(t[end:], "else {")
    dc = lines_between(t, "// Remove DC Offset with single pole HP", "processed_sample_r = temp_sample;")
    mix = lines_between(t, "// Calculate dry/wet mix", "processed_sample_r = processed_sample_r*output_gain;")
    mix = "\n".join(l for l in mix.splitlines() if "out_amplitude" not in l)  # (the meter)
    body = "\n".join([
        "// GENERATED by make-golden.py from libs/ghostblock-sub/subhoofer/src/lib.rs (Subhoofer v2.2.3, GPL-3.0-or-later,",
        "// Copyright Ardura). Everything between the BEGIN / END lines is upstream's text, byte for byte.",
        "#[derive(PartialEq, Eq, Debug, Copy, Clone)]",
        "// ---- BEGIN upstream: enum AlgorithmType (without nih-plug's #[name] attributes)", enum, "// ---- END",
    ] + ["// ---- BEGIN upstream fn\n" + f + "\n// ---- END" for f in fns] + [
        "pub struct Subhoofer { pub buffer: [f32; 16], pub prev_processed_in_r: f32, pub prev_processed_out_r: f32, pub prev_processed_in_l: f32, pub prev_processed_out_l: f32 }",
        "impl Subhoofer {",
        "    #[allow(clippy::too_many_arguments)]",
        "    pub fn process_harmonics(&mut self, in_l_arg: f32, in_r_arg: f32, overall_scale: f32, h_algorithm: AlgorithmType, harmonics: f32, hoof_hardness: f32,",
        "                             custom_harmonics1: f32, custom_harmonics2: f32, custom_harmonics3: f32, custom_harmonics4: f32, dry_wet: f32, output_gain: f32) -> (f32, f32) {",
        "        let mut in_l = in_l_arg; let mut in_r = in_r_arg;",
        "        let sub_bump: f32 = 0.0; let sub_gain: f32 = 0.0; // (the subharmonic generator is not part of the port)",
        "        let mut processed_sample_l: f32; let mut processed_sample_r: f32;",
        "        // ---- BEGIN upstream: Normalize really small values", "        " + small, "        // ---- END",
        "        // ---- BEGIN upstream: Add: Original signal + Harmonics + Sub signal", "        " + match, "        // ---- END",
        "        // ---- BEGIN upstream: Hardness Saturation", "        " + hard_if + " " + hard_else, "        // ---- END",
        "        // ---- BEGIN upstream: DC high-pass", "        " + dc, "        // ---- END",
        "        // ---- BEGIN upstream: dry/wet, output gain", "        " + mix, "        // ---- END",
        "        (processed_sample_l, processed_sample_r)",
        "    }",
        "}", ""])
    open(os.path.join(HERE, "src", "upstream_extract.rs"), "w", encoding="utf-8").write(body)
    env = dict(os.environ, CARGO_NET_OFFLINE="true")
    target = os.environ.get("P2SUB_REF_TARGET", os.path.join(HERE, "target"))
    r = subprocess.run(["cargo", "run", "--release", "--quiet", "--offline", "--manifest-path", os.path.join(HERE, "Cargo.toml"), "--target-dir", target],
                       env=env, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        sys.exit("cargo failed")
    head = ("// Subhoofer v2.2.3 (commit 19ea26b500fe0f3fc0516bde02b565af80501ae6), lib.rs sha256 %s\n" % PIN[LIB])
    text = head + r.stdout
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8").read()
        print("golden header: " + ("identical to a fresh run of the Rust reference" if have == text else "DIFFERS from a fresh run"))
        sys.exit(0 if have == text else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote %s (%d bytes)" % (os.path.normpath(OUT), len(text)))


if __name__ == "__main__":
    main()
