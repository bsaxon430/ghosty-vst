// Poltergeist 2 (GhostBlock) - SUB: runs upstream Subhoofer's harmonic path (its own Rust text, see
// upstream_extract.rs, written by ../make-golden.py from libs/ghostblock-sub/subhoofer/src/lib.rs) over a fixed set of
// inputs and settings and prints the results as a C++ header: the golden values the C++ port must reproduce.
#![allow(non_snake_case, dead_code, unused_variables, unused_mut, unused_assignments, non_camel_case_types)]
use std::f32::consts::PI;
mod util;
#[path = "../../subhoofer/src/SweetenX.rs"]
mod SweetenX; // upstream's file itself

include!("upstream_extract.rs");

const N: usize = 160;

// the inputs: integer and polynomial arithmetic only, so every platform makes the same bits
fn inputs() -> (Vec<f32>, Vec<f32>) {
    let mut l = vec![0.0f32; N];
    let mut r = vec![0.0f32; N];
    let mut s: u32 = 0x1234_5678;
    for i in 0..N {
        if i < N / 2 {
            // a one-sided bump every 37 (left) / 29 (right) samples, like a window-function pulse train
            let p = ((i % 37) as f32) / 37.0;
            let q = ((i % 29) as f32) / 29.0;
            l[i] = 16.0 * p * p * (1.0 - p) * (1.0 - p) - 0.3;
            r[i] = 0.5 - 16.0 * q * q * (1.0 - q) * (1.0 - q);
        } else {
            s = s.wrapping_mul(1664525).wrapping_add(1013904223);
            l[i] = ((s >> 8) as f32) / 8388608.0 - 1.0;
            s = s.wrapping_mul(1664525).wrapping_add(1013904223);
            r[i] = ((s >> 8) as f32) / 8388608.0 - 1.0;
        }
    }
    (l, r)
}

fn main() {
    let (l, r) = inputs();
    let algos = [
        AlgorithmType::ABass3,
        AlgorithmType::ABass2,
        AlgorithmType::BBass,
        AlgorithmType::CBass,
        AlgorithmType::TanH,
        AlgorithmType::CustomSliders,
    ];
    let harmonics = [0.000580f32, 0.02, 0.3];
    let scales = [1.0f32, 192000.0 / 44100.0];
    let pairs = [(0.0093f32, 0.35f32), (0.2, 1.0)]; // (hoof hardness, input gain as a factor)
    println!("// GENERATED by libs/ghostblock-sub/reference/make-golden.py - do not edit.");
    println!("// Upstream Subhoofer's harmonic path (rustc, its own source text) on {} stereo samples per case.", N);
    println!("struct SubhooferGoldenCase {{ int algo; float harmonics, hardness, scale, gain; }};");
    let mut cases = String::new();
    let mut data = String::new();
    let mut ncase = 0;
    for (ai, a) in algos.iter().enumerate() {
        for h in harmonics.iter() {
            for sc in scales.iter() {
                for (hard, gain) in pairs.iter() {
                    let mut st = Subhoofer {
                        buffer: [0.0; 16],
                        prev_processed_in_r: 0.0,
                        prev_processed_out_r: 0.0,
                        prev_processed_in_l: 0.0,
                        prev_processed_out_l: 0.0,
                    };
                    cases.push_str(&format!(
                        "    {{{}, {:e}f, {:e}f, {:e}f, {:e}f}},\n",
                        ai, h, hard, sc, gain
                    ));
                    for i in 0..N {
                        let (ol, or) = st.process_harmonics(
                            l[i] * *gain, r[i] * *gain, *sc, *a, *h, *hard, 3.0, 20.0, 40.0, 7.0, 0.8, 1.25,
                        );
                        data.push_str(&format!("0x{:08x},0x{:08x},", ol.to_bits(), or.to_bits()));
                        if i % 6 == 5 {
                            data.push('\n');
                        }
                    }
                    data.push('\n');
                    ncase += 1;
                }
            }
        }
    }
    println!("static const int kSubhooferGoldenN = {};", N);
    println!("static const int kSubhooferGoldenCases = {};", ncase);
    println!("static const SubhooferGoldenCase kSubhooferGoldenCase[] = {{\n{}}};", cases);
    // the custom strengths, the dry/wet and the output gain every case runs with
    println!("static const float kSubhooferGoldenCustom[4] = {{3.0f, 20.0f, 40.0f, 7.0f}};");
    println!("static const float kSubhooferGoldenDryWet = 0.8f, kSubhooferGoldenOutGain = 1.25f;");
    println!("static const unsigned int kSubhooferGolden[] = {{\n{}}};", data);
    // the free functions on a few values of their own (bit patterns: input, drive, result)
    let xs = [0.0f32, 1.0e-9, -0.013, 0.25, -0.5, 0.71, 1.0, -1.7, 3.2];
    let ds = [0.0f32, 0.0093, 0.3, 1.0];
    let mut f = String::new();
    let mut nf = 0;
    for x in xs.iter() {
        for d in ds.iter() {
            let v = [
                chebyshev_tape(*x, *d),
                tape_saturation(*x, *d),
                b_bass_saturation(*x, *d),
                c_bass_saturation(*x, *d),
                custom_sincos_saturation(*x, *d * 31.0, *d * 189.0, *d * 25.0, *d * 26.0),
                leaf_saturation(*x, util::db_to_gain(-30.0), *d),
            ];
            f.push_str(&format!("0x{:08x},0x{:08x},", x.to_bits(), d.to_bits()));
            for q in v.iter() {
                f.push_str(&format!("0x{:08x},", q.to_bits()));
            }
            f.push('\n');
            nf += 1;
        }
    }
    println!("static const int kSubhooferGoldenFnRows = {};", nf);
    println!("static const unsigned int kSubhooferGoldenFn[] = {{\n{}}};", f);
}
