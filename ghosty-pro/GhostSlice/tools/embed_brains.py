#!/usr/bin/env python3
# Ghost Slice build 6: the melody brain's data, embedded as gzip'd byte arrays (one mechanism for every compiler and the hand build).
#   ArpEZator/data/recipe.json   Professor Bernstein's ArpEZator recipe (our own)
#   GhostSlice/data/brain_pop.json   n-gram models learned from POP909 (MIT, Music X Lab) - Block Step / Ghost House's own models
#   GhostSlice/data/brain_acid.json  the Aicd 303 model (MIT, Michael Ganss)
# usage: python3 tools/embed_brains.py  (from ghosty-pro/GhostSlice) -> BrainData.inc
import gzip, os, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
items = [("arp_recipe", os.path.join(root, "..", "ArpEZator", "data", "recipe.json")),
         ("brain_pop", os.path.join(root, "data", "brain_pop.json")),
         ("brain_acid", os.path.join(root, "data", "brain_acid.json"))]
out = ["// GENERATED by tools/embed_brains.py - do not edit. gzip'd JSON (decompressed once, on first use)."]
for name, path in items:
    raw = open(path, "rb").read(); z = gzip.compress(raw, 9, mtime=0)
    out.append("static const unsigned char k_%s[%d] = {" % (name, len(z)))
    for i in range(0, len(z), 40):
        out.append("".join("%d," % b for b in z[i:i + 40]))
    out.append("};")
open(os.path.join(root, "BrainData.inc"), "w").write("\n".join(out) + "\n")
print("BrainData.inc written")
