#!/usr/bin/env python3
"""Fits Ghost Hum's beatbox network (HumBeatNet.h: 963 -> 64 -> 32 -> 6) on feature rows written by HumBench.

  train_beat.py <feat_dir> <out_dir> [--folds 4] [--epochs 60] [--seed 1]

<feat_dir> holds HumBench's rows (kIn + 1 float32 each, the label last: 0..4 = KICK SNARE HI-HAT OPEN HAT CLAP, 5 = NOT A DRUM):
  avp_P<n>_*.bin   real amateur beatboxers (AVP dataset, CC BY 4.0; HumBench beatfeat), grouped by participant
  synth_*.bin      our own synthesised mouths (HumBench synthfeat): the claps, more variety, mouth noise as NOT A DRUM
Writes, in <out_dir>:
  fold<k>.bin      a net trained WITHOUT the participants of fold k (the benchmark scores each participant with the net that never heard them)
  all.bin          the net trained on everyone (what ships)
  HumBeatNetWeights.h   all.bin as C++ (copy into ghosty-pro/GhostHum/)
  cv.json          held-out per-hit accuracy per fold
Weights file format: float32 W1 (64 x 802, row-major), b1, W2 (32 x 64), b2, W3 (6 x 32), b3.
Nothing here ships but the numbers; torch is only the fitting tool.
"""
import sys, os, glob, re, json, argparse
import numpy as np
import torch, torch.nn as nn

KIN, H1, H2, KOUT = 963, 64, 32, 6
NAMES = ["KICK", "SNARE", "HI-HAT", "OPEN HAT", "CLAP", "NOT A DRUM"]

def load(p):
    a = np.fromfile(p, dtype=np.float32)
    return a.reshape(-1, KIN + 1) if a.size else np.zeros((0, KIN + 1), np.float32)

def participant(p):
    m = re.search(r"avp_P(\d+)_", os.path.basename(p)); return int(m.group(1)) if m else -1

class Net(nn.Module):
    def __init__(s):
        super().__init__(); s.l1 = nn.Linear(KIN, H1); s.l2 = nn.Linear(H1, H2); s.l3 = nn.Linear(H2, KOUT); s.dr = nn.Dropout(0.25)
    def forward(s, x):
        h = torch.relu(s.l1(x)); h = s.dr(h); h = torch.relu(s.l2(h)); return s.l3(s.dr(h))

def augment(x):
    # the patch part (first 800) is log10 levelled to its peak, clipped at -6: a little level noise, a random spectral tilt (another
    # mouth / mic), and now and then a floor raised (a noisier room)
    x = x.clone(); n = x.shape[0]; P = x[:, :960].view(n, 24, 40)
    tilt = (torch.rand(n, 1, 1) - 0.5) * 0.6 * torch.linspace(-1, 1, 40).view(1, 1, 40)
    P = P + tilt + torch.randn_like(P) * 0.08
    floor = -6 + torch.rand(n, 1, 1) * 3 * (torch.rand(n, 1, 1) < 0.3).float()
    P = torch.maximum(P, floor); P = P - P.amax(dim=(1, 2), keepdim=True); P = torch.clamp(P, min=-6)
    x[:, :960] = P.reshape(n, 960); x[:, 960] += torch.randn(n) * 0.1
    return x

def fit(X, y, epochs, seed):
    torch.manual_seed(seed); np.random.seed(seed); net = Net(); opt = torch.optim.AdamW(net.parameters(), lr=2e-3, weight_decay=1e-3)
    cnt = np.bincount(y, minlength=KOUT).astype(np.float64); w = (cnt.sum() / np.maximum(1, cnt)) ** 0.5; w = w / w.mean()
    lossf = nn.CrossEntropyLoss(weight=torch.tensor(w, dtype=torch.float32), label_smoothing=0.05)
    Xt = torch.tensor(X); yt = torch.tensor(y, dtype=torch.long); n = len(y)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=3e-3, total_steps=epochs * ((n + 255) // 256))
    for ep in range(epochs):
        net.train(); perm = torch.randperm(n)
        for i in range(0, n, 256):
            idx = perm[i:i + 256]; xb = augment(Xt[idx]); loss = lossf(net(xb), yt[idx]); opt.zero_grad(); loss.backward(); opt.step(); sched.step()
    net.eval(); return net

def predict(net, X):
    with torch.no_grad(): return torch.softmax(net(torch.tensor(X)), 1).numpy()

def save_bin(net, path):
    parts = [net.l1.weight, net.l1.bias, net.l2.weight, net.l2.bias, net.l3.weight, net.l3.bias]
    np.concatenate([p.detach().numpy().astype(np.float32).ravel() for p in parts]).tofile(path)

def save_header(net, path, note):
    def arr(name, t):
        v = t.detach().numpy().astype(np.float32).ravel()
        body = ",".join(("%.5g" % f).replace("e-0", "e-") + "f" for f in v)
        lines = [body[i:i + 4000] for i in range(0, len(body), 4000)]
        # (break only at commas)
        out, cur = [], ""
        for tok in body.split(","):
            if len(cur) + len(tok) > 180: out.append(cur); cur = ""
            cur += tok + ","
        out.append(cur)
        return "    static const float %s[%d] = {\n%s\n    };\n" % (name, v.size, "\n".join("        " + l for l in out))
    with open(path, "w") as f:
        f.write("#pragma once\n// GHOST HUM - BEATBOX build 4: the network's numbers. GENERATED by tests/bench/train_beat.py - do not edit by hand.\n")
        f.write("// %s\n" % note)
        f.write("// Trained on the Amateur Vocal Percussion dataset (Delgado et al. 2019, CC BY 4.0: only these learned numbers ship, no audio)\n// and on our own synthesised beatbox mouths (tests/HumVoices.h).\n")
        f.write('#include "HumBeatNet.h"\n\nnamespace hum::beat2 {\n\ninline const Net& defaultNet() {\n    static const Net N = [] {\n')
        for name, t in (("W1", net.l1.weight), ("b1", net.l1.bias), ("W2", net.l2.weight), ("b2", net.l2.bias), ("W3", net.l3.weight), ("b3", net.l3.bias)):
            f.write(arr("k" + name, t))
        f.write("        Net n; n.W1.assign(kW1, kW1 + %d); n.b1.assign(kb1, kb1 + %d); n.W2.assign(kW2, kW2 + %d); n.b2.assign(kb2, kb2 + %d); n.W3.assign(kW3, kW3 + %d); n.b3.assign(kb3, kb3 + %d);\n" % (H1 * KIN, H1, H2 * H1, H2, KOUT * H2, KOUT))
        f.write("        return n; }();\n    return N;\n}\n\n} // namespace hum::beat2\n")

def net_from_bin(path):
    v = np.fromfile(path, dtype=np.float32); net = Net(); o = 0
    for p in (net.l1.weight, net.l1.bias, net.l2.weight, net.l2.bias, net.l3.weight, net.l3.bias):
        n = p.numel(); p.data = torch.tensor(v[o:o + n]).view_as(p); o += n
    assert o == v.size; return net

def main():
    if len(sys.argv) == 4 and sys.argv[1] == "--bin2h": save_header(net_from_bin(sys.argv[2]), sys.argv[3], "converted from " + os.path.basename(sys.argv[2])); return
    ap = argparse.ArgumentParser(); ap.add_argument("feat"); ap.add_argument("out"); ap.add_argument("--folds", type=int, default=4); ap.add_argument("--epochs", type=int, default=60); ap.add_argument("--seed", type=int, default=1); ap.add_argument("--synth-x", dest="synth_x", type=int, default=1)   # (how many times the synthesised rows count)
    a = ap.parse_args(); os.makedirs(a.out, exist_ok=True); torch.set_num_threads(2)
    avp = {}
    for p in sorted(glob.glob(os.path.join(a.feat, "avp_P*.bin"))): avp.setdefault(participant(p), []).append(load(p))
    avp = {k: np.concatenate(v) for k, v in avp.items()}
    syn_tr = np.concatenate([load(p) for p in glob.glob(os.path.join(a.feat, "synth_train*.bin"))])
    syn_te = np.concatenate([load(p) for p in glob.glob(os.path.join(a.feat, "synth_test*.bin"))]) if glob.glob(os.path.join(a.feat, "synth_test*.bin")) else syn_tr[:0]
    people = sorted(avp); folds = [people[i::a.folds] for i in range(a.folds)]
    print("participants %d, avp rows %d, synth rows %d / %d" % (len(people), sum(len(v) for v in avp.values()), len(syn_tr), len(syn_te)))
    cv = {"folds": []}; conf_all = np.zeros((KOUT, KOUT), int)
    for k, test in enumerate(folds):
        tr = np.concatenate([avp[p] for p in people if p not in test] + [syn_tr] * a.synth_x); te = np.concatenate([avp[p] for p in test])
        net = fit(tr[:, :KIN], tr[:, KIN].astype(int), a.epochs, a.seed + k); save_bin(net, os.path.join(a.out, "fold%d.bin" % k))
        # every 3rd row is the un-jittered patch (HumBench writes at, at-1, at+1 for each labelled hit; junk rows once): score all rows
        pr = predict(net, te[:, :KIN]).argmax(1); yt = te[:, KIN].astype(int)
        for t, p in zip(yt, pr): conf_all[t, p] += 1
        drum = yt < 5; acc = float((pr[drum] == yt[drum]).mean()); junk_ok = float((pr[~drum] == 5).mean()) if (~drum).any() else float("nan"); kept = float((pr[drum] != 5).mean())
        cv["folds"].append({"test": test, "drum_acc": acc, "junk_rejected": junk_ok, "drums_kept": kept}); print("fold %d (P %s): right drum %.3f, drums kept %.3f, junk rejected %.3f" % (k, test, acc, kept, junk_ok))
    if len(syn_te):
        pr = predict(net, syn_te[:, :KIN]).argmax(1); yt = syn_te[:, KIN].astype(int); d = yt < 5
        cv["synth_test"] = {"drum_acc": float((pr[d] == yt[d]).mean()), "clap_acc": float((pr[yt == 4] == 4).mean()) if (yt == 4).any() else None}; print("synth test (last fold net):", cv["synth_test"])
    cv["confusion"] = conf_all.tolist(); print("held-out confusion (rows truth, cols guess):", *NAMES, sep="  "); print(conf_all)
    tr = np.concatenate(list(avp.values()) + [syn_tr] * a.synth_x); net = fit(tr[:, :KIN], tr[:, KIN].astype(int), a.epochs, a.seed + 99)
    save_bin(net, os.path.join(a.out, "all.bin")); save_header(net, os.path.join(a.out, "HumBeatNetWeights.h"), "963 -> 64 -> 32 -> 6, %d rows, %d epochs, seed %d" % (len(tr), a.epochs, a.seed))
    json.dump(cv, open(os.path.join(a.out, "cv.json"), "w"), indent=1)

if __name__ == "__main__": main()
